CREATE TABLE IF NOT EXISTS role (
  role_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(50) NOT NULL,
  CONSTRAINT uq_role_name UNIQUE (role_name)
);

CREATE TABLE IF NOT EXISTS category (
  category_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name VARCHAR(100) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_category_name ON category (LOWER(category_name));

CREATE TABLE IF NOT EXISTS supplier (
  supplier_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_name  VARCHAR(50) NOT NULL,
  contact_number VARCHAR(30) DEFAULT NULL,
  email          VARCHAR(50) DEFAULT NULL,
  address        VARCHAR(80) DEFAULT NULL
);

CREATE TABLE IF NOT EXISTS users (
  user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id       INT NOT NULL,
  username      VARCHAR(50) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  first_name    VARCHAR(50) NOT NULL,
  last_name     VARCHAR(50) NOT NULL,
  is_active     SMALLINT NOT NULL DEFAULT 1,
  CONSTRAINT chk_users_is_active CHECK (is_active IN (0, 1)),
  CONSTRAINT fk_user_role FOREIGN KEY (role_id)
    REFERENCES role (role_id) ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username ON users (LOWER(username));
CREATE INDEX IF NOT EXISTS idx_user_role ON users (role_id);

CREATE TABLE IF NOT EXISTS product (
  product_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id    INT NOT NULL,
  product_name   VARCHAR(50) NOT NULL,
  sku            VARCHAR(30) NOT NULL,
  unit_price     NUMERIC(10,2) NOT NULL,
  cost_price     NUMERIC(10,2) NOT NULL,
  reorder_level  INT NOT NULL DEFAULT 10,
  stock_quantity INT NOT NULL DEFAULT 0,
  status         VARCHAR(10) NOT NULL DEFAULT 'active',
  CONSTRAINT fk_product_category FOREIGN KEY (category_id)
    REFERENCES category (category_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT chk_product_status CHECK (status IN ('active', 'inactive')),
  CONSTRAINT chk_product_cost_price CHECK (cost_price >= 0),
  CONSTRAINT chk_product_reorder_level CHECK (reorder_level >= 0),
  CONSTRAINT chk_product_stock CHECK (stock_quantity >= 0),
  CONSTRAINT chk_product_unit_price CHECK (unit_price >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_product_sku ON product (LOWER(sku));
CREATE INDEX IF NOT EXISTS idx_product_category ON product (category_id);
CREATE INDEX IF NOT EXISTS idx_product_stock ON product (stock_quantity);
CREATE INDEX IF NOT EXISTS idx_product_status ON product (status);

CREATE TABLE IF NOT EXISTS product_supplier (
  product_id            INT NOT NULL,
  supplier_id           INT NOT NULL,
  supplier_product_code VARCHAR(30) DEFAULT NULL,
  supply_price          NUMERIC(10,2) NOT NULL,
  PRIMARY KEY (product_id, supplier_id),
  CONSTRAINT fk_ps_product FOREIGN KEY (product_id)
    REFERENCES product (product_id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_ps_supplier FOREIGN KEY (supplier_id)
    REFERENCES supplier (supplier_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT chk_supply_price CHECK (supply_price >= 0)
);
CREATE INDEX IF NOT EXISTS idx_ps_supplier ON product_supplier (supplier_id);

CREATE TABLE IF NOT EXISTS sale (
  sale_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INT NOT NULL,
  sale_date    TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  discount     NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  total_amount NUMERIC(12,2) NOT NULL,
  CONSTRAINT fk_sale_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT chk_sale_discount CHECK (discount >= 0),
  CONSTRAINT chk_sale_total CHECK (total_amount >= 0)
);
CREATE INDEX IF NOT EXISTS idx_sale_date ON sale (sale_date);
CREATE INDEX IF NOT EXISTS idx_sale_user ON sale (user_id);

CREATE TABLE IF NOT EXISTS sale_item (
  sale_id    BIGINT NOT NULL,
  product_id INT NOT NULL,
  quantity   INT NOT NULL,
  unit_price NUMERIC(10,2) NOT NULL,
  discount   NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  subtotal   NUMERIC(12,2) NOT NULL,
  PRIMARY KEY (sale_id, product_id),
  CONSTRAINT fk_sale_item_product FOREIGN KEY (product_id)
    REFERENCES product (product_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_sale_item_sale FOREIGN KEY (sale_id)
    REFERENCES sale (sale_id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT chk_sale_item_discount CHECK (discount >= 0),
  CONSTRAINT chk_sale_item_price CHECK (unit_price >= 0),
  CONSTRAINT chk_sale_item_quantity CHECK (quantity > 0),
  CONSTRAINT chk_sale_item_subtotal CHECK (subtotal >= 0)
);
CREATE INDEX IF NOT EXISTS idx_sale_item_product ON sale_item (product_id);

CREATE TABLE IF NOT EXISTS inventory_movement (
  movement_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id       INT NOT NULL,
  user_id          INT NOT NULL,
  movement_type    VARCHAR(10) NOT NULL,
  quantity         INT NOT NULL,
  movement_date    TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reference_number VARCHAR(100) DEFAULT NULL,
  remarks          VARCHAR(255) DEFAULT NULL,
  CONSTRAINT fk_movement_product FOREIGN KEY (product_id)
    REFERENCES product (product_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_movement_user FOREIGN KEY (user_id)
    REFERENCES users (user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT chk_movement_type CHECK (movement_type IN ('STOCK_IN', 'STOCK_OUT', 'ADJUSTMENT', 'RETURN')),
  CONSTRAINT chk_movement_quantity CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS idx_movement_user ON inventory_movement (user_id);
CREATE INDEX IF NOT EXISTS idx_inventory_product ON inventory_movement (product_id);
CREATE INDEX IF NOT EXISTS idx_inventory_date ON inventory_movement (movement_date);
CREATE INDEX IF NOT EXISTS idx_inventory_type ON inventory_movement (movement_type);
CREATE INDEX IF NOT EXISTS idx_inventory_product_date ON inventory_movement (product_id, movement_date);

CREATE TABLE IF NOT EXISTS app_settings (
  setting_key   VARCHAR(100) PRIMARY KEY,
  setting_value VARCHAR(255) NOT NULL
);
